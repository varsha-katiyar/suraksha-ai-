@router.post("/report")
async def report_road_damage(
    lat: float = Form(...),
    lon: float = Form(...),
    damage_type: str = Form(...),
    description: str = Form(""),
    photo: Optional[UploadFile] = File(None)
):
    """
    Step 1 & 2: Receive report and verify via Gemini Vision.
    """
    try:
        db = load_db()
        if "road_scars" not in db: db["road_scars"] = []
        if "road_scar_clusters" not in db: db["road_scar_clusters"] = []
        if "road_scar_drafts" not in db: db["road_scar_drafts"] = []

        report_id = str(uuid.uuid4())
        
        # Mock Gemini Verification
        is_verified = gemini_verify_mock(description, damage_type)
        
        report = {
            "id": report_id,
            "lat": lat,
            "lon": lon,
            "damage_type": damage_type,
            "description": description,
            "is_verified": is_verified,
            "clustered": False,
            "created_at": datetime.now().isoformat()
        }
        db["road_scars"].append(report)
        
        # Step 3: Threshold check (Cluster reports within 100m)
        if is_verified:
            nearby_verified = [
                r for r in db["road_scars"] 
                if r["is_verified"] and not r.get("clustered", False) and 
                haversine_m(lat, lon, r["lat"], r["lon"]) <= 100
            ]
            
            # If 3 or more verified reports in the same zone
            if len(nearby_verified) >= 3:
                cluster_id = str(uuid.uuid4())
                
                for r in nearby_verified:
                    r["clustered"] = True
                    r["cluster_id"] = cluster_id
                
                cluster = {
                    "id": cluster_id,
                    "lat": lat,
                    "lon": lon,
                    "reports": [r["id"] for r in nearby_verified],
                    "created_at": datetime.now().isoformat()
                }
                db["road_scar_clusters"].append(cluster)
                
                # Step 4 & 5: Auto Complaint Drafting & Dispatch
                ref_id = await file_complaint(nearby_verified, damage_type, lat, lon)
                
                draft = {
                    "id": ref_id,
                    "cluster_id": cluster_id,
                    "agency": "NHAI / PWD",
                    "lat": lat,
                    "lon": lon,
                    "damage_type": damage_type,
                    "status": "Sent via Email",
                    "created_at": datetime.now().isoformat(),
                    "pdf_path": f"uploads/complaint_{ref_id}.pdf"
                }
                
                db["road_scar_drafts"].append(draft)
                
                save_db(db)
                return {
                    "status": "success", 
                    "message": "Damage verified. Threshold reached. Complaint auto-drafted and sent to NHAI.",
                    "draft_id": draft["id"]
                }
                
        save_db(db)
        return {"status": "success", "message": "Damage logged and verified.", "verified": is_verified}
        
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))

@router.get("/status")
async def get_pipeline_status():
    """
    Returns pipeline status for the admin dashboard.
    """
    db = load_db()
    return {
        "reports": db.get("road_scars", []),
        "clusters": db.get("road_scar_clusters", []),
        "drafts": db.get("road_scar_drafts", [])
    }

@router.get("/complaint-pdf/{cluster_id}")
async def get_complaint_pdf(cluster_id: str):
    """
    Returns the actual PDF document generated by reportlab.
    """
    db = load_db()
    drafts = db.get("road_scar_drafts", [])
    draft = next((d for d in drafts if d.get("cluster_id") == cluster_id), None)
    
    if draft and "pdf_path" in draft and os.path.exists(draft["pdf_path"]):
        return FileResponse(draft["pdf_path"], media_type="application/pdf", filename=f"Complaint_{draft['id']}.pdf")
        
    raise HTTPException(status_code=404, detail="PDF not found")

