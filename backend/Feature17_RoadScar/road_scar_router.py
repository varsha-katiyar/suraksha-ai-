def haversine_m(lat1, lon1, lat2, lon2):
    """Returns distance in meters"""
    R = 6371000.0
    phi1, phi2 = math.radians(lat1), math.radians(lat2)
    dphi = math.radians(lat2 - lat1)
    dlambda = math.radians(lon2 - lon1)
    a = math.sin(dphi/2)**2 + math.cos(phi1)*math.cos(phi2)*math.sin(dlambda/2)**2
    return 2 * R * math.asin(math.sqrt(a))

def gemini_verify_mock(description: str, damage_type: str) -> bool:
    """
    Mocking Gemini Vision Verification.
    In production: pass image_bytes to genai.GenerativeModel('gemini-1.5-pro-vision')
    For the demo, we assume verification passes if it's a valid damage type.
    """
    valid_types = ['pothole', 'broken_divider', 'waterlogging', 'missing_signage']
    return damage_type.lower() in valid_types or 'dangerous' in description.lower()

